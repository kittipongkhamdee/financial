-- =============================================================================
-- ตารางอัตราเงินอุดหนุนรายหัวทางการ (สพฐ.) — master data อ้างอิง แยกจากตัวเลขจริง
-- ที่โรงเรียนกรอกใน plan_revenue_lines เพื่อใช้เป็นค่าเริ่มต้นตอนตั้งปีงบประมาณใหม่
-- อัตราประกาศใหม่ทุกปีจากสำนักนโยบายและแผนการศึกษาขั้นพื้นฐาน สพฐ. จึงเก็บแยกตามปี
-- =============================================================================

create table if not exists public.plan_official_rates (
  id               uuid primary key default gen_random_uuid(),
  year             int  not null,   -- ปีงบประมาณ พ.ศ. ที่อัตรานี้บังคับใช้ตามประกาศ
  revenue_type_id  uuid not null references public.plan_revenue_types (id) on delete restrict,
  level_label      text not null,   -- ระดับชั้น เช่น "มัธยมศึกษาตอนต้น" / "มัธยมศึกษาปีที่ 1"
  rate_per_student numeric(12, 2) not null check (rate_per_student >= 0),
  note             text not null default '',   -- เช่น "(สถานประกอบการ)" สำหรับอัตรา ปวช. ทวิภาคี — default '' ไม่ใช่ null กัน unique constraint เพี้ยน (null ไม่เท่ากับ null)
  sort_order       int  not null default 0,
  unique (year, revenue_type_id, level_label, note)
);

alter table public.plan_official_rates enable row level security;

drop policy if exists plan_admin_all on public.plan_official_rates;
create policy plan_admin_all on public.plan_official_rates
  for all to authenticated
  using (public.asset_current_role() = 'admin')
  with check (public.asset_current_role() = 'admin');

