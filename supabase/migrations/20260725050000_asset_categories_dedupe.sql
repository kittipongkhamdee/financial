-- ลบหมวดครุภัณฑ์ชื่อเดิม (ไม่มีคำนำหน้า "ครุภัณฑ์") ที่ตกค้างจากการย้ายชื่อในมิเกรชันก่อนหน้า
-- เพราะ on conflict (name) จับคู่ไม่ได้เมื่อชื่อเปลี่ยน ทำให้เกิดแถวซ้ำ — ยังไม่มีรายการครุภัณฑ์ใดอ้างอิงแถวเหล่านี้

delete from public.asset_categories
where name in (
  'คอมพิวเตอร์', 'โฆษณาและเผยแพร่', 'งานบ้านงานครัว',
  'ไฟฟ้าและวิทยุ', 'การศึกษา', 'วิทยาศาสตร์และการแพทย์'
)
and id not in (select category_id from public.asset_items where category_id is not null);
